# Criar uma branch via git ultilizando como nome anp01
git branch anp01

# Criar uma branch via git ultilizando como nome anp02
git branch anp02

# Alternar para a branch anp01
git checkout anp01

# Adicionar as mudanças da branch anp01
git add .

# Criar um commit com a mensagem "adicionando o arquivo anp01"
git commit -m "adicionando novas classes a projeto C#"

# Efetuar o push da branch anp01
git push origin anp01

# Merge com a branch main
git merge main